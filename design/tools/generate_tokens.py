#!/usr/bin/env python3
"""Generate MD3 color tokens (light/dark) for the Kurisa design prototype.

Source of truth: HCT tonal palettes (Material Color Utilities), role->tone mapping
per references/design-tokens.md of the md3e skill.

Usage:
    python3 -m venv .venv && .venv/bin/pip install material-color-utilities
    .venv/bin/python tools/generate_tokens.py

Seed concept: Material You blue derived from the reference app, with a green
tertiary reserved for progress / downloaded states.
"""
import json
import os

try:
    from material_color_utilities import TonalPalette
except ImportError:
    raise SystemExit("pip install material-color-utilities")

# Palette seeds are HCT (hue, chroma). They reproduce the reference app's
# Material You blue: primary tone40 = #0058CA, tone80 = #B0C6FF,
# neutral tone99 = #FEFBFF, tone10 = #1B1B1F.
PALETTES = {
    "primary": (268.5, 63),
    "secondary": (268.5, 18),
    "tertiary": (145.6, 52),
    "neutral": (268, 4),
    "neutralVariant": (268, 8),
    "error": (25, 84),
}

def hx(tp, tone):
    v = tp.get(tone)
    return ("#" + v.lstrip("#")).upper() if isinstance(v, str) else ("#" + v.hex.lstrip("#")).upper()

TP = {k: TonalPalette(h, c) for k, (h, c) in PALETTES.items()}

def role(name, light_tone, dark_tone, palette="primary"):
    return name, {"light": hx(TP[palette], light_tone), "dark": hx(TP[palette], dark_tone)}

ROLES = {}
def add(*pairs):
    for name, v in pairs:
        ROLES[name] = v

add(
    role("primary", 40, 80),
    role("onPrimary", 100, 20),
    role("primaryContainer", 90, 30),
    role("onPrimaryContainer", 10, 90),
    role("inversePrimary", 80, 40),
    role("primaryFixed", 90, 90),
    role("primaryFixedDim", 80, 80),
    role("onPrimaryFixed", 10, 10),
    role("onPrimaryFixedVariant", 30, 30),
    role("secondary", 40, 80, "secondary"),
    role("onSecondary", 100, 20, "secondary"),
    role("secondaryContainer", 90, 30, "secondary"),
    role("onSecondaryContainer", 10, 90, "secondary"),
    role("secondaryFixed", 90, 90, "secondary"),
    role("secondaryFixedDim", 80, 80, "secondary"),
    role("onSecondaryFixed", 10, 10, "secondary"),
    role("onSecondaryFixedVariant", 30, 30, "secondary"),
    role("tertiary", 40, 80, "tertiary"),
    role("onTertiary", 100, 20, "tertiary"),
    role("tertiaryContainer", 90, 30, "tertiary"),
    role("onTertiaryContainer", 10, 90, "tertiary"),
    role("tertiaryFixed", 90, 90, "tertiary"),
    role("tertiaryFixedDim", 80, 80, "tertiary"),
    role("onTertiaryFixed", 10, 10, "tertiary"),
    role("onTertiaryFixedVariant", 30, 30, "tertiary"),
    role("error", 40, 80, "error"),
    role("onError", 100, 20, "error"),
    role("errorContainer", 90, 30, "error"),
    role("onErrorContainer", 10, 90, "error"),
    role("background", 99, 10, "neutral"),
    role("onBackground", 10, 90, "neutral"),
    role("surface", 99, 10, "neutral"),
    role("onSurface", 10, 90, "neutral"),
    role("surfaceVariant", 90, 30, "neutralVariant"),
    role("onSurfaceVariant", 30, 80, "neutralVariant"),
    role("surfaceTint", 40, 80, "primary"),
    role("inverseSurface", 20, 90, "neutral"),
    role("inverseOnSurface", 95, 20, "neutral"),
    role("outline", 50, 60, "neutralVariant"),
    role("outlineVariant", 80, 30, "neutralVariant"),
    role("scrim", 0, 0, "neutral"),
    role("surfaceDim", 87, 6, "neutral"),
    role("surfaceBright", 98, 24, "neutral"),
    role("surfaceContainerLowest", 100, 4, "neutral"),
    role("surfaceContainerLow", 96, 10, "neutral"),
    role("surfaceContainer", 94, 12, "neutral"),
    role("surfaceContainerHigh", 92, 17, "neutral"),
    role("surfaceContainerHighest", 90, 22, "neutral"),
)

def kebab(s):
    out = []
    for i, ch in enumerate(s):
        if ch.isupper() and i:
            out.append("-")
        out.append(ch.lower())
    return "".join(out)

here = os.path.dirname(os.path.abspath(__file__))
css_path = os.path.join(here, "..", "assets", "tokens.css")
js_path = os.path.join(here, "..", "assets", "tokens.js")

lines = ["/* AUTO-GENERATED by tools/generate_tokens.py — do not edit by hand. */",
         "/* HCT palettes: primary(268.5,63) secondary(268.5,18) tertiary(145.6,52) neutral(268,4) neutralVariant(268,8) error(25,84) */",
         ":root {"]
for name, v in ROLES.items():
    lines.append(f"  --md-{kebab(name)}: {v['light']};")
lines.append("}")
lines.append("")
lines.append('[data-theme="dark"] {')
for name, v in ROLES.items():
    lines.append(f"  --md-{kebab(name)}: {v['dark']};")
lines.append("}")
lines.append("")
with open(css_path, "w") as f:
    f.write("\n".join(lines))

with open(js_path, "w") as f:
    f.write("window.MD3_TOKENS = " + json.dumps(ROLES, indent=1) + ";\n")

print(f"wrote {css_path}")
print(f"wrote {js_path}")
print("primary light", ROLES["primary"]["light"], "| dark", ROLES["primary"]["dark"])
print("tertiary light", ROLES["tertiary"]["light"], "| surfaceLight", ROLES["surface"]["light"], "| surfaceDark", ROLES["surface"]["dark"])
